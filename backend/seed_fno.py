def seed_stocks():
    created = 0
    skipped = 0
    for symbol in fno_stocks:
        obj, was_created = Stock.objects.get_or_create(
            symbol=symbol,
            defaults={
                'name': symbol,
                'sector': 'Unknown',
                'is_fno': True,
                'lot_size': 1
            }
        )
        if was_created:
            created += 1
            print(f"Created: {symbol}")
        else:
            skipped += 1
    print(f"\nDone! Created: {created}, Skipped (already exists): {skipped}")

if __name__ == '__main__':
    seed_stocks()
